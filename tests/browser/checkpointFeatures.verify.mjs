import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox','--enable-unsafe-swiftshader'] })
const page = await browser.newPage(), errors = [], results = []
page.on('dialog', dialog => dialog.accept())
page.on('pageerror', error => errors.push(String(error)))
await page.route('https://api.mapbox.com/**', route => route.fulfill({json: {version:8,sources:{},layers:[]}}))
await fs.mkdir('work/checkpoint-features-browser', {recursive:true})
for (const width of [1440,768,390,320]) {
  await page.setViewportSize({width,height:900})
  await page.goto(`${process.env.TEDIX_BROWSER_URL || 'http://127.0.0.1:5173'}/tests/browser/creatorPositions.html`)
  const nav = page.getByRole('navigation', {name:'Hunt Features'})
  await nav.waitFor()
  assert.equal(await nav.getByRole('button').count(), 7)
  assert.equal(await page.getByRole('spinbutton',{name:'Total checkpoint count'}).inputValue(),'7')
  await page.getByText('Checkpoint 7 is the FinishPoint.',{exact:true}).waitFor()
  const featureArticle = nav.locator('xpath=following-sibling::article')
  assert.equal(await featureArticle.locator('#checkpoint-positions').count(),1)
  assert.equal(await page.locator('#checkpoint-positions').count(),1)
  await page.getByRole('spinbutton',{name:'Total checkpoint count'}).fill('8')
  assert.equal(await page.locator('[data-checkpoint]').count(),8)
  await page.getByRole('spinbutton',{name:'Total checkpoint count'}).fill('7')
  assert.equal(await page.locator('[data-checkpoint]').count(),7)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth||document.querySelector('main').scrollWidth>innerWidth),false)
  await featureArticle.getByRole('button',{name:'Save & continue',exact:true}).click()
  await page.getByText('Feature 2 of 7',{exact:true}).waitFor()
  assert.equal(await page.locator('#checkpoint-positions').count(),0)
  for (const name of ['Personal Challenge','Team Challenge']) {
    await nav.getByRole('button',{name:new RegExp(name)}).click()
    const terminal=page.getByRole('button',{name:'Checkpoint 7, FinishPoint',exact:true})
    assert.equal(await terminal.isEnabled(),true)
    assert.match(await terminal.textContent(),/FinishPoint 🚩/)
    await terminal.focus(); await page.keyboard.press('Enter')
    if (name === 'Personal Challenge' && await page.getByRole('button',{name:'Edit existing challenges',exact:true}).count()) await page.getByRole('button',{name:'Edit existing challenges',exact:true}).click()
    await page.getByRole('combobox',{name,exact:true}).selectOption(name==='Personal Challenge'?'square':'hypothesis')
    if (name === 'Personal Challenge') await page.getByRole('button',{name:'Use this challenge',exact:true}).click()
    await page.getByRole('button',{name:'Create Your Own',exact:true}).click()
    await page.getByRole('region',{name:`${name} authoring`,exact:true}).waitFor()
    await page.getByRole('button',{name:'Predefined',exact:true}).click()
    if (name === 'Personal Challenge' && [1440,320].includes(width)) await nav.locator('xpath=..').screenshot({path:`work/checkpoint-features-browser/terminal-${width}.png`})
  }
  await nav.getByRole('button',{name:/Next Checkpoint/}).click()
  const terminal=page.getByRole('button',{name:'Checkpoint 7, FinishPoint',exact:true})
  assert.equal(await terminal.isDisabled(),true)
  await page.getByText('The FinishPoint has no next checkpoint.',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Checkpoint 6',exact:true}).click()
  await page.getByRole('combobox',{name:'Navigation',exact:true}).selectOption('signal-strength')
  await page.getByRole('button',{name:'Previous',exact:true}).last().click()
  await page.getByText('Feature 3 of 7',{exact:true}).waitFor()
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth||document.querySelector('main').scrollWidth>innerWidth)
  assert.equal(overflow,false)
  results.push({width,sevenSteps:true,positioningInsideFeatureOne:true,countResizesPositioning:true,continueWithoutVerification:true,terminalChallenges:true,terminalNavigationDisabled:true,checkpointSixNavigation:true,overflow})
  await page.screenshot({path:`work/checkpoint-features-browser/${width}.png`})
}
assert.deepEqual(errors,[])
await fs.writeFile('work/checkpoint-features-browser/results.json',JSON.stringify({results,errors},null,2))
console.log(JSON.stringify({results,errors},null,2))
await browser.close()
