import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const output = process.env.SCREENSHOT_DIR || 'work/creator-map-restore'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--enable-unsafe-swiftshader'] })
const results = []
try {
for (const width of [1440, 390]) {
 const page = await browser.newPage({ viewport: { width, height: 1000 }, reducedMotion: 'reduce', hasTouch: true })
 const errors = []; page.on('pageerror', e => errors.push(e.message))
 await page.route('https://api.mapbox.com/**', route => {
  const url = route.request().url()
  if (url.includes('/suggest')) return route.fulfill({ json: { suggestions: [{ mapbox_id: 'fixture', name: 'Cluj test square', full_address: 'Controlled browser search result' }] } })
  if (url.includes('/retrieve')) return route.fulfill({ json: { features: [{ geometry: { coordinates: [23.604, 46.771] } }] } })
  return route.fulfill({ json: { version: 8, sources: {}, layers: [{ id: 'fixture-background', type: 'background', paint: { 'background-color': url.includes('satellite') ? '#586358' : '#e8eeeb' } }] } })
 })
 await page.route('https://events.mapbox.com/**', r => r.fulfill({ json: {} }))
 const section = name => page.getByRole('navigation', { name: 'Creator sections' }).getByRole('button', { name, exact: true }).click()
 await page.goto(`${process.env.BASE_URL || 'http://127.0.0.1:5173'}/tests/browser/huntSetup.html?offline`)
 await page.getByRole('button', { name: 'Continue to Template builder' }).click()
 await section('Checkpoints & Challenges')
 if (process.env.BEFORE) {
  assert.equal(await page.locator('#checkpoint-positions').count(), 0)
  await page.screenshot({ path: `${output}/before-${width}.png`, fullPage: true })
  results.push({ width, beforeMapAbsent: true }); await page.close(); continue
 }
 await page.locator('.mapboxgl-canvas').waitFor()
 await page.waitForFunction(() => window.fixtureMap?.isStyleLoaded())
 const center = await page.evaluate(() => window.fixtureMap.getCenter().toArray())
 assert.ok(Math.abs(center[0] - 23.6236) < .001 && Math.abs(center[1] - 46.7712) < .001)
 await page.screenshot({ path: `${output}/after-${width}.png`, fullPage: true })
 assert.equal(await page.locator('[data-checkpoint="F"]').count(), 1)
 assert.equal(await page.locator('.position-checkpoints [data-checkpoint]').count(), 7)
 const search = page.getByRole('combobox', { name: 'Search locations' })
 await search.fill('Cluj test')
 await page.getByRole('listbox').getByRole('option').getByRole('button').click()
 await page.waitForTimeout(1400)
 await page.locator('[data-checkpoint="1"]').click()
 await page.locator('.mapboxgl-canvas').click({ position: { x: 140, y: 300 } })
 const values = () => page.locator('.position-values').innerText()
 const placed = await values()
 await page.getByRole('button', { name: 'Confirm position', exact: true }).click()
 await page.getByRole('button', { name: 'Undo last position change' }).click()
 await page.getByRole('button', { name: 'Redo last position change' }).click()
 await page.locator('[data-checkpoint="1"]').click()
 assert.equal(await values(), placed.replace('Locally edited · unconfirmed', 'Confirmed'))
 const beforeDrag = await page.locator('.position-values dd').nth(2).innerText()
 const pin = page.locator('[data-position-pin="1"]')
 const box = await pin.boundingBox()
 await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
 await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 30, box.y + box.height / 2 + 25, { steps: 8 }); await page.mouse.up()
 assert.notEqual(await page.locator('.position-values dd').nth(2).innerText(), beforeDrag)
 const edited = await values()
 await page.screenshot({ path: `${output}/positioned-${width}.png`, fullPage: true })
 await page.locator('summary').filter({ hasText: 'Arrival verification & safety reminders' }).click()
 assert.equal(await page.locator('.position-editor input[type="checkbox"]').count(), 6)
 await page.getByRole('button', { name: 'Satellite', exact: true }).click()
 await page.waitForFunction(() => window.fixtureMap.isStyleLoaded())
 const camera = await page.evaluate(() => ({ center: window.fixtureMap.getCenter().toArray(), zoom: window.fixtureMap.getZoom() }))
 await page.getByRole('button', { name: 'Edit', exact: true }).click()
 await page.getByLabel('Name:', { exact: true }).fill('Pending CP name')
 await section('Template Setup'); await section('Advanced'); await section('Checkpoints & Challenges')
 assert.equal(await page.getByLabel('Name:', { exact: true }).inputValue(), 'Pending CP name')
 await page.getByRole('button', { name: 'Cancel', exact: true }).click()
 await page.waitForFunction(() => window.fixtureMap.isStyleLoaded())
 assert.equal(await values(), edited)
 const restored = await page.evaluate(() => ({ center: window.fixtureMap.getCenter().toArray(), zoom: window.fixtureMap.getZoom() }))
 assert.deepEqual(restored, camera)
 await page.locator('[data-checkpoint="F"]').click()
 await page.getByRole('button', { name: 'Edit', exact: true }).click()
 await page.getByLabel('Name:', { exact: true }).fill('Finish square')
 await page.getByRole('button', { name: 'Save changes', exact: true }).click()
 await page.locator('.mapboxgl-canvas').click({ position: { x: 150, y: 320 } })
 await page.getByRole('button', { name: 'Confirm position', exact: true }).click()
 await page.evaluate(() => window.fixtureMap.fire('error', { error: new Error('Fixture network outage') }))
 await page.getByRole('button', { name: 'Retry map' }).click()
 await page.waitForFunction(() => window.fixtureMap.isStyleLoaded())
 await page.waitForFunction(() => !document.querySelector('[role="alert"]')?.textContent?.includes('Map could not load'))
 await section('Review & Submit')
 await page.getByRole('button', { name: 'Run template validation' }).click()
 assert.equal(await page.getByRole('button', { name: 'Submit for Approval' }).isDisabled(), true)
 await page.goto('http://127.0.0.1:5173/tests/browser/huntSetup.html')
 await page.getByRole('button', { name: 'Select registered locality' }).click()
 await page.getByLabel('Country *', { exact: true }).selectOption('FR')
 await page.getByLabel('Region *', { exact: true }).selectOption('11')
 await page.getByLabel('City *', { exact: true }).fill('Paris')
 await page.getByRole('button', { name: /Paris.*France/ }).click()
 await page.getByRole('button', { name: 'Continue to Template builder' }).click()
 await section('Checkpoints & Challenges')
 await page.waitForFunction(() => window.fixtureMap?.isStyleLoaded())
 const paris = await page.evaluate(() => window.fixtureMap.getCenter().toArray())
 assert.ok(Math.abs(paris[0] - 2.3522) < .001 && Math.abs(paris[1] - 48.8566) < .001)
 await page.getByRole('button', { name: 'Recenter map' }).click()
 await page.goto('http://127.0.0.1:5173/tests/browser/huntSetup.html?existing')
 await section('Checkpoints & Challenges')
 await page.locator('.mapboxgl-canvas').waitFor()
 await page.locator('[data-checkpoint="1"]').click()
 assert.match(await values(), /48.8606/)
 assert.equal(await page.locator('.mapboxgl-canvas').count(), 1)
 assert.deepEqual(errors, [])
 results.push({ width, provisionalCluj: true, search: true, placement: true, dragging: true, undoRedoConfirmation: true, satellite: true, navigationPreservesEditsAndCamera: true, finishPoint: true, errorRecovery: true, invalidSubmissionBlocked: true, canonicalSelectorAndCenter: true, savedPositions: true })
 await page.close()
}
await writeFile(`${output}/results.json`, JSON.stringify({ controlledMapboxResponses: true, results }, null, 2))
console.log(JSON.stringify(results))
} finally { await browser.close() }
