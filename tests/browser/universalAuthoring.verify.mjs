import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage(), errors = [], measurements = []
page.on('pageerror', error => errors.push(String(error)))
await fs.mkdir('work/universal-authoring-browser', { recursive: true })
for (const width of [1440,768,390,320]) {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('http://127.0.0.1:5173/tests/browser/universalAuthoring.html')
  await page.evaluate(() => sessionStorage.clear())
  const title = page.getByRole('textbox', { name: 'Template name', exact: true })
  await title.fill(`Reusable mystery ${width}`); await title.focus(); await page.keyboard.press('Tab')
  assert.equal(await page.getByRole('textbox', { name: 'Short description', exact: true }).evaluate(node => document.activeElement === node), true)
  await page.keyboard.press('Shift+Tab'); assert.equal(await title.evaluate(node => document.activeElement === node), true)
  assert.equal((await page.locator('main').textContent()).includes('Route reviewed this session'), false)
  const save = page.getByRole('button', { name: 'Save draft', exact: true })
  await save.click(); await page.getByText('Saving Template…', { exact: true }).first().waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => window.fixtureCalls.filter(call => call.method === 'create').length), 1)
  const submit = page.getByRole('button', { name: 'Submit version to Admin', exact: true })
  assert.equal(await submit.isEnabled(), true)
  await title.fill(`Saved revision ${width}`); assert.equal(await submit.isEnabled(), false)
  await save.click(); await page.getByText('Universal Template · Draft · Version 2', { exact: true }).waitFor()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.querySelector('main').scrollWidth > innerWidth)
  assert.equal(overflow, false); measurements.push({ width, overflow })
  await page.locator('main').evaluate(node => node.scrollTo(0,0))
  await page.screenshot({ path: `work/universal-authoring-browser/editor-${width}.png`, fullPage: true })
  await page.goto('http://127.0.0.1:5173/tests/browser/universalAuthoring.html?open=1')
  await title.waitFor(); assert.equal(await title.inputValue(), `Saved revision ${width}`)
  await submit.focus(); await page.keyboard.press('Enter')
  await page.getByText('Version 2 submitted for Admin review', { exact: true }).waitFor()
  assert.equal(await page.locator('input,textarea,select').count(), 0)
  const calls = await page.evaluate(() => window.fixtureCalls)
  assert.equal(calls.filter(call => call.method === 'submit').length, 1)
  assert.equal(calls.find(call => call.method === 'submit').version, 2)
}
assert.deepEqual(errors, [])
console.log(JSON.stringify({ measurements, errors }))
await browser.close()
