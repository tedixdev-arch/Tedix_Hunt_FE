import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage(); page.setDefaultTimeout(10000)
const errors = [], results = []
page.on('pageerror', error => errors.push(String(error)))
page.on('dialog', dialog => dialog.accept())
const output = 'docs/evidence/personal-challenge-builder'
await fs.mkdir(output, { recursive: true })
const feature = () => page.getByRole('navigation', { name: 'Hunt Features', exact: true }).getByRole('button', { name: /Personal Challenge/ }).click()
const panel = () => page.getByRole('region', { name: 'Personal Challenge authoring', exact: true })
async function checkLayout() {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'page overflow')
  assert.equal(await panel().evaluate(node => node.scrollWidth > node.clientWidth), false, 'editor overflow')
}
async function screenshot(type, width, scene) {
  await checkLayout()
  const focus = scene === 'test' ? panel().locator(`[aria-label="${type} interactive exercise"]`) : scene === 'predefined' ? panel() : panel().getByRole('button', { name: 'Edit with Preview', exact: true })
  await focus.evaluate(node => node.scrollIntoView({ block: 'start', behavior: 'instant' }))
  await page.screenshot({ path: `${output}/${type}-${width}-${scene}.png` })
}
async function solve(type, e) {
  const play = panel().locator(`[aria-label="${type} interactive exercise"]`)
  const d = e.interaction, a = e.answer
  if (type === 'tap-pair') {
    const cards = play.getByLabel('Tap and pair cards').getByRole('button')
    for (const pair of a.pairs) {
      await cards.nth(d.left.findIndex(x => x.id === pair.leftId)).click()
      await cards.nth(d.left.length + [...d.right].reverse().findIndex(x => x.id === pair.rightId)).click()
    }
  } else if (type === 'single-choice') await play.getByRole('button', { name: d.options.find(x => x.id === a.optionId).text, exact: true }).click()
  else for (const answer of a.values) await play.getByRole('textbox').nth(d.blanks.findIndex(x => x.id === answer.blankId)).fill(answer.value)
  await play.getByRole('button', { name: 'Check answer', exact: true }).click()
  assert.equal(await play.getByRole('status').textContent(), e.feedback.correct)
  await play.getByRole('button', { name: 'Reset', exact: true }).click()
  assert.equal(await play.getByRole('status').count(), 0)
}
for (const width of [1440, 768, 390, 320]) for (const type of ['tap-pair', 'single-choice', 'fill-blank']) {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('http://127.0.0.1:5173/tests/browser/customPersistence.html')
  await page.waitForFunction(() => window.exercises?.length === 22)
  await feature()
  await panel().getByRole('button', { name: 'Predefined', exact: true }).click()
  await panel().getByRole('combobox', { name: 'Personal Challenge', exact: true }).selectOption(type)
  assert.equal(await panel().getByRole('combobox').count(), 1)
  assert.equal(await panel().getByRole('textbox').count(), 0)
  const initial = await page.evaluate(() => window.fixtureRecord())
  await screenshot(type, width, 'predefined')
  await panel().getByRole('button', { name: 'Test Challenge', exact: true }).click()
  const preset = await page.evaluate(async type => {
    const { predefinedPersonal } = await import('/src/features/creator/exercises/predefinedPersonal.ts')
    const { toPersistence } = await import('/src/features/creator/exercises/persistenceAdapter.ts')
    return toPersistence(predefinedPersonal.find(e => e.type === type))
  }, type)
  await solve(type, preset)
  await panel().getByRole('button', { name: 'Return to Edit', exact: true }).click()
  assert.deepEqual(await page.evaluate(() => window.fixtureRecord()), initial)
  await panel().getByRole('button', { name: 'Use this challenge', exact: true }).click()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Template version saved by the backend' }).waitFor()
  const predefinedSaved = await page.evaluate(() => window.fixtureRecord())
  assert.equal(predefinedSaved.content.checkpoints[0].personalChallengePreset, type)
  assert.equal(predefinedSaved.content.checkpoints[0].customExercises.personal.owner.version, 4)
  assert.equal(predefinedSaved.content.checkpoints[0].kind, initial.content.checkpoints[0].kind)
  await page.evaluate(() => window.fixtureReopen()); await feature()
  assert.equal(await panel().getByRole('textbox').count(), 0)
  await page.getByRole('button', { name: 'Checkpoint 2', exact: true }).click()
  await page.waitForFunction(type => document.querySelector(`[aria-label="Personal Challenge authoring"] option[value="${type}"]`)?.disabled, type)
  assert.equal(await panel().locator(`option[value="${type}"]`).evaluate(option => option.disabled), true)
  await page.getByRole('button', { name: 'Checkpoint 1', exact: true }).click()
  await panel().getByRole('button', { name: 'Create Your Own', exact: true }).click()
  assert.equal(await panel().getByRole('combobox', { name: 'Personal Challenge', exact: true }).inputValue(), type)
  await panel().getByLabel('Title', { exact: true }).fill(`My ${type} challenge`)
  const editorInput = panel().locator('input[type="text"], input:not([type])').first()
  await editorInput.fill('My visible card, choice or question')
  await screenshot(type, width, 'step-by-step')
  await panel().getByRole('button', { name: 'Next', exact: true }).click()
  await panel().getByRole('button', { name: 'Next', exact: true }).click()
  assert.match(await panel().textContent(), /Review and test/)
  await panel().getByRole('button', { name: 'Edit with Preview', exact: true }).click()
  assert.equal(await editorInput.inputValue(), 'My visible card, choice or question')
  await screenshot(type, width, 'visual-edit')
  // Keyboard-only alternative to dragging preserves card identities and answer links.
  await panel().getByRole('button', { name: 'Move row 1 down', exact: true }).focus(); await page.keyboard.press('Enter')
  await panel().getByRole('button', { name: 'Move row 2 up', exact: true }).click()
  await panel().getByRole('button', { name: 'Apply to Hunt', exact: true }).click()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Template version saved by the backend' }).waitFor()
  const customSaved = await page.evaluate(() => window.fixtureRecord())
  const e = customSaved.content.checkpoints[0].customExercises.personal
  assert.equal(customSaved.content.checkpoints[0].personalChallengePreset, undefined)
  assert.equal(e.title, `My ${type} challenge`); assert.equal(e.owner.version, 5)
  assert.notEqual(e.id, predefinedSaved.content.checkpoints[0].customExercises.personal.id)
  assert.deepEqual(customSaved.content.checkpoints.slice(1), initial.content.checkpoints.slice(1))
  await panel().getByRole('button', { name: 'Test Challenge', exact: true }).click()
  await solve(type, e)
  await screenshot(type, width, 'test')
  await panel().getByRole('button', { name: 'Return to Edit', exact: true }).click()
  assert.equal(await editorInput.inputValue(), 'My visible card, choice or question')
  assert.deepEqual(await page.evaluate(() => window.fixtureRecord()), customSaved)
  await page.evaluate(() => window.fixtureReopen()); await feature()
  assert.equal(await panel().getByLabel('Title', { exact: true }).inputValue(), e.title)
  assert.equal(await panel().locator('input[type="text"], input:not([type])').first().inputValue(), 'My visible card, choice or question')
  await checkLayout()
  results.push({ type, width, predefined: true, readOnly: true, duplicateDisabled: true, sharedDraft: true, keyboardReorder: true, inlineTest: true, saveReload: true, overflow: false })
}
await fs.writeFile('docs/evidence/Personal_Challenge_Builder_Browser_Results.json', JSON.stringify({ results, errors, backend: 'Mocked Template operations; live integration unverified' }, null, 2))
await browser.close()
assert.deepEqual(errors, [])
console.log(`${results.length} Personal Challenge builder scenarios passed; ${errors.length} page errors`)
