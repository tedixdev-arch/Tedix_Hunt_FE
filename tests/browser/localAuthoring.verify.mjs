import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
const page = await browser.newPage(), errors=[], measurements=[]
page.on('pageerror',error=>errors.push(String(error)))
await fs.mkdir('work/local-browser',{recursive:true})
for(const width of [1440,768,390,320]) {
  await page.setViewportSize({width,height:900})
  await page.goto('http://127.0.0.1:5173/tests/browser/localAuthoring.html')
  await page.getByRole('button',{name:/^Create Local Template/}).focus();await page.keyboard.press('Enter')
  await page.getByRole('link',{name:'Start from scratch',exact:true}).click()
  const title=page.getByRole('textbox',{name:'Template name',exact:true})
  await title.fill(`Local mystery ${width}`);await title.focus();await page.keyboard.press('Tab')
  assert.equal(await page.getByRole('textbox',{name:'Short description',exact:true}).evaluate(node=>document.activeElement===node),true)
  await page.keyboard.press('Shift+Tab');assert.equal(await title.evaluate(node=>document.activeElement===node),true)
  const save=page.getByRole('button',{name:'Save draft',exact:true})
  await save.click();await page.getByText('Local Template · Draft · Version 1',{exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>window.fixtureCalls.filter(c=>c.method==='create')[0].category),'local')
  const geo=page.getByRole('region',{name:'Local geography'})
  await geo.getByRole('combobox',{name:'Country',exact:true}).selectOption('RO')
  await geo.getByRole('textbox').fill('Town')
  await geo.getByRole('button',{name:/Original town · Northern/}).focus();await page.keyboard.press('Enter')
  await save.click();await page.getByText('Local Template · Draft · Version 2',{exact:true}).waitFor()
  await page.evaluate(()=>window.registryName='Corrected registry town')
  await geo.getByRole('button',{name:'Use current registry details on next save',exact:true}).click()
  await save.click();await page.getByText('Local Template · Draft · Version 3',{exact:true}).waitFor()
  assert.equal((await geo.textContent()).includes('Corrected registry town'),true)
  await geo.getByRole('button',{name:'Clear locality',exact:true}).click();await save.click();await page.getByText('Local Template · Draft · Version 4',{exact:true}).waitFor()
  assert.equal(await geo.getByText('No locality saved.',{exact:true}).count(),1)
  await page.goto('http://127.0.0.1:5173/tests/browser/localAuthoring.html?open=1');await title.waitFor();assert.equal(await title.inputValue(),`Local mystery ${width}`)
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth||document.querySelector('main').scrollWidth>innerWidth)
  assert.equal(overflow,false);measurements.push({width,overflow})
  await geo.scrollIntoViewIfNeeded()
  await page.screenshot({path:`work/local-browser/editor-${width}.png`,fullPage:true})
  await page.goto('http://127.0.0.1:5173/tests/browser/localAuthoring.html')
  await page.getByRole('button',{name:/^Create Local Template/}).click();await page.getByRole('button',{name:'Start from an approved Universal',exact:true}).click()
  await page.getByRole('button',{name:'View approved Template',exact:true}).click();await page.getByRole('button',{name:'Use as Local Template',exact:true}).click()
  await page.getByRole('textbox',{name:'New destination key'}).fill(`copy-${width}`)
  await page.getByRole('button',{name:'Create Local draft',exact:true}).focus();await page.keyboard.press('Enter')
  await title.waitFor();assert.equal(await title.inputValue(),'Shared approved story')
  const copy=await page.evaluate(()=>window.fixtureCalls.find(c=>c.method==='copy'))
  assert.deepEqual(copy.publishedReference,{templateId:'22222222-2222-4222-8222-222222222222',version:2})
  assert.equal(await geo.getByText('No locality saved.',{exact:true}).count(),1)
}
assert.deepEqual(errors,[])
await fs.writeFile('work/local-browser/results.json',JSON.stringify({measurements,errors},null,2));console.log(JSON.stringify({measurements,errors}));await browser.close()
