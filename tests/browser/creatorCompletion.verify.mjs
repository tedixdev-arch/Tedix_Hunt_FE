import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage(), errors = [], results = []
page.on('pageerror', error => errors.push(String(error)))
await fs.mkdir('work/completion-browser', { recursive: true })
const go = query => page.goto(`http://127.0.0.1:5173/tests/browser/creatorCompletion.html?${query}`)
const button = name => page.getByRole('button', { name, exact: true })
for (const width of [1440, 768, 390, 320]) {
  await page.setViewportSize({ width, height: 900 })
  await go('incomplete=1')
  const geo = page.getByRole('region', { name: 'Local geography' })
  await button('Run template validation').click(); await button('Review checkpoint positions').click()
  await page.getByText('Place and name each numbered checkpoint exactly once in Checkpoint Positions. Set valid coordinates and a radius from 5 to 500 metres.', { exact: true }).waitFor()
  await geo.getByRole('combobox', { name: 'Country', exact: true }).selectOption('RO')
  await button("Can't find your locality?").focus(); await page.keyboard.press('Enter')
  assert.equal(await button("Can't find your locality?").getAttribute('aria-expanded'), 'true')
  const localityName = page.getByRole('textbox', { name: 'Locality name', exact: true })
  await localityName.fill('Independent town'); await localityName.focus(); await page.keyboard.press('Tab')
  assert.equal(await page.getByRole('textbox', { name: 'Administrative context', exact: true }).evaluate(n => n === document.activeElement), true)
  await page.keyboard.press('Shift+Tab'); assert.equal(await localityName.evaluate(n => n === document.activeElement), true)
  await page.getByRole('textbox', { name: 'Administrative context', exact: true }).fill('Northern county')
  await page.getByRole('spinbutton', { name: 'Latitude', exact: true }).fill('46')
  await page.getByRole('spinbutton', { name: 'Longitude', exact: true }).fill('23')
  await page.getByRole('textbox', { name: 'Why is this locality missing?', exact: true }).fill('This settlement is missing from the registry.')
  await page.getByRole('textbox', { name: 'Independent supporting evidence', exact: true }).fill('Independent official gazetteer 2026 entry 123.')
  await button('Send locality proposal').focus(); await page.keyboard.press('Enter')
  await page.getByText('Pending review — not selectable', { exact: true }).waitFor()
  assert.equal(await button('Find approved locality in registry').count(), 0)
  await page.evaluate(() => window.approveProposal()); await button('Refresh proposals').click()
  await button('Find approved locality in registry').click(); await button('Save draft').click()
  await page.getByText('Local Template · Draft · Version 4', { exact: true }).waitFor()
  assert.equal(await button('Submit version to Admin').isDisabled(), true)
  await button("Can't find your locality?").click() // Save reuses the inline component and keeps disclosure open.
  await button("Can't find your locality?").click()
  await geo.scrollIntoViewIfNeeded(); await page.screenshot({ path: `work/completion-browser/proposals-${width}.png`, fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.querySelector('main').scrollWidth > innerWidth), false)
  for (const type of ['local', 'universal']) {
    await go(`list=1&type=${type}&status=changes_requested${type === 'local' ? '&suspended=1' : ''}`)
    await page.getByRole('link', { name: 'Revise', exact: true }).focus(); await page.keyboard.press('Enter')
    await page.getByRole('textbox', { name: 'Template name', exact: true }).fill(`Revised ${type} ${width}`)
    await button('Save draft').click(); await page.getByText(`${type === 'local' ? 'Local' : 'Universal'} Template · Draft · Version 4`, { exact: true }).waitFor()
    if (type === 'local') { await button('Run template validation').click(); await button('✓ Validation passed').waitFor(); assert.match(await page.locator('main').textContent(), /Suspended.*Access temporarily closed/) }
    assert.equal(await button('Submit version to Admin').isDisabled(), false)
    await button('Submit version to Admin').focus(); await page.keyboard.press('Enter')
    await page.getByText('Version 4 submitted for Admin review', { exact: true }).waitFor()
    const state = await page.evaluate(() => ({ calls: window.fixtureCalls, record: window.fixtureRecord() }))
    assert.equal(state.calls.filter(c => c.method === 'version').length, 1)
    assert.equal(state.calls.find(c => c.method === 'submit').version, 4)
    assert.equal(type === 'local' ? state.record.localApprovedVersion : state.record.publishedVersion, 2)
    if (type === 'local') assert.equal(state.record.localSuspension.reason, 'Access temporarily closed')
    assert.equal(await page.getByRole('textbox', { name: 'Template name', exact: true }).count(), 0)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.querySelector('main').scrollWidth > innerWidth), false)
    await page.screenshot({ path: `work/completion-browser/submitted-${type}-${width}.png`, fullPage: true })
  }
  results.push({ width, keyboard: 'Enter/Tab/Shift+Tab passed', overflow: false, proposals: 'pending and approved registry read passed', revisions: 'Universal/Local exact v4 submission, retained v2, suspension passed' })
}
assert.deepEqual(errors, [])
await fs.writeFile('work/completion-browser/results.json', JSON.stringify({ results, errors }, null, 2))
console.log(JSON.stringify({ results, errors })); await browser.close()
