import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage()
const errors = [], requests = [], measurements = []
page.on('pageerror', error => errors.push(String(error)))
page.on('request', request => { if (!['GET', 'HEAD'].includes(request.method())) requests.push(request.url()) })
const output = 'work/creator-studio-browser'
await fs.mkdir(output, { recursive: true })
for (const width of [1440, 768, 390, 320]) {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('http://127.0.0.1:5173/tests/browser/creatorStudio.html')
  const trigger = page.getByRole('button', { name: '+ Create Template', exact: true })
  await trigger.waitFor()
  assert.equal(await page.getByRole('heading', { name: 'Creator Studio', exact: true }).count(), 1)
  assert.equal(await page.getByRole('navigation', { name: 'Creator Studio entries' }).count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Create Legacy Template', exact: true }).isVisible(), false)
  const measure = await page.evaluate(() => ({ width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth || document.querySelector('main').scrollWidth > innerWidth }))
  measurements.push(measure); assert.equal(measure.overflow, false)
  if ([1440, 390].includes(width)) await page.screenshot({ path: `${output}/studio-${width}.png` })
  await trigger.focus(); await page.keyboard.press('Enter')
  const panel = page.getByRole('dialog')
  const universal = panel.getByRole('link', { name: /^Universal Template/ })
  await universal.waitFor()
  assert.equal(await universal.getAttribute('href'), '/create?category=universal')
  assert.equal(await universal.evaluate(node => document.activeElement === node), true)
  await page.keyboard.press('Shift+Tab')
  assert.equal(await panel.getByRole('button', { name: 'Cancel' }).evaluate(node => document.activeElement === node), true)
  await page.keyboard.press('Tab')
  assert.equal(await universal.evaluate(node => document.activeElement === node), true)
  await page.keyboard.press('Tab'); await page.keyboard.press('Enter')
  await panel.getByRole('button', { name: 'Start from an approved Universal' }).waitFor()
  assert.equal(await panel.getByRole('link', { name: 'Start from scratch' }).getAttribute('href'), '/create?category=local')
  assert.equal(await panel.evaluate(node => node.scrollWidth > node.clientWidth), false)
  if ([1440, 390].includes(width)) await page.screenshot({ path: `${output}/local-${width}.png` })
  await panel.getByRole('button', { name: '← Back to template types' }).click()
  await universal.waitFor()
  await page.keyboard.press('Escape')
  await panel.waitFor({ state: 'detached' })
  await page.waitForFunction(button => document.activeElement === button, await trigger.elementHandle())
  await trigger.click(); await panel.waitFor()
  await page.goBack(); await panel.waitFor({ state: 'detached' })
  await page.goForward(); await panel.waitFor()
  await panel.getByRole('button', { name: 'Cancel' }).click()
  await page.getByText('Legacy compatibility', { exact: true }).click()
  await page.getByRole('button', { name: 'Create Legacy Template', exact: true }).click()
  await panel.getByRole('button', { name: 'Start from Template', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  for (const state of ['loading', 'error', 'populated']) {
    await page.goto(`http://127.0.0.1:5173/tests/browser/creatorStudio.html?state=${state}`)
    if (state === 'loading') await page.getByText('Loading Creator Templates…', { exact: true }).waitFor()
    if (state === 'error') await page.getByRole('alert').waitFor()
    if (state === 'populated') {
      assert.equal(await page.getByRole('region', { name: 'Creator Templates', exact: true }).getByRole('article').count(), 3)
      for (const type of ['Universal', 'Local', 'Legacy']) assert.equal(await page.getByText(type, { exact: true }).count(), 1)
      if ([1440, 390].includes(width)) await page.screenshot({ path: `${output}/populated-${width}.png` })
    }
    assert.equal(await page.evaluate(() => document.querySelector('main').scrollWidth > innerWidth), false)
  }
}
assert.deepEqual(errors, []); assert.deepEqual(requests, [])
await fs.writeFile(`${output}/results.json`, JSON.stringify({ measurements, errors, mutationRequests: requests }, null, 2))
console.log(JSON.stringify({ measurements, errors, mutationRequests: requests }, null, 2))
await browser.close()
