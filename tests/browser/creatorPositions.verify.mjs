const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']})
const page = await browser.newPage({viewport:{width:1440,height:1000},hasTouch:true})
const errors=[]
page.on('pageerror',e=>errors.push(String(e)))
await page.route('https://api.mapbox.com/**',async route=> {
  if(route.request().url().includes('/styles/')) return route.fulfill({json:{version:8,sources:{},layers:[{id:'mock-background',type:'background',paint:{'background-color':'#e8eeeb'}}]}})
  if(route.request().url().includes('/suggest')) return route.fulfill({json:{suggestions:[{mapbox_id:'fixture',name:'Preview arrival area',full_address:'Local mocked search result'}]}})
  if(route.request().url().includes('/retrieve')) return route.fulfill({json:{features:[{geometry:{coordinates:[23.604,46.771]}}]}})
  return route.fulfill({json:{}})
})
await page.goto('http://127.0.0.1:5173/tests/browser/creatorPositions.html')
await page.locator('#checkpoint-positions').scrollIntoViewIfNeeded()
await page.locator('.mapboxgl-canvas').waitFor()
await page.waitForTimeout(600)
const measurements=[]
const output='work/checkpoint-positions-browser'
await fs.mkdir(output,{recursive:true})
for(const width of [1440,1280,768,390,360,320]) {
  await page.setViewportSize({width,height:width<640?2800:1800})
  await page.reload()
  await page.locator('#checkpoint-positions').scrollIntoViewIfNeeded()
  await page.locator('.mapboxgl-canvas').waitFor()
  await page.waitForTimeout(600)
  await page.locator('.position-editor').evaluate(el=>el.parentElement.closest('section').scrollIntoView({block:'start'}))
  await page.locator('[data-checkpoint="4"]').click()
  await page.waitForTimeout(200)
  const measure=await page.evaluate(()=>{
    const rect=s=>{const r=document.querySelector(s).getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height}}
    const main=document.querySelector('main')
    return {width:innerWidth,pageOverflow:document.documentElement.scrollWidth>innerWidth,mainOverflow:main.scrollWidth>main.clientWidth,map:rect('.position-map'),workspace:rect('.position-workspace'),list:rect('.position-checkpoints'),inspector:rect('.position-inspector'),rows:[...document.querySelectorAll('.position-checkpoint')].map(b=>b.getBoundingClientRect().height),toolbar:[...document.querySelectorAll('.position-toolbar button')].map(b=>({label:b.getAttribute('aria-label')||b.textContent,width:b.getBoundingClientRect().width,height:b.getBoundingClientRect().height}))}
  })
  measurements.push(measure)
  assert.ok(!measure.pageOverflow && !measure.mainOverflow,`No overflow at ${width}`)
  assert.ok(measure.list.y >= measure.map.y+measure.map.h-2)
  assert.ok(measure.inspector.y >= measure.map.y+measure.map.h-2)
  if(width>=640) { assert.ok(measure.inspector.x>measure.list.x); assert.ok(measure.rows.every(h=>h>=32&&h<=36)) }
  else { assert.ok(measure.inspector.y>measure.list.y); assert.ok(measure.rows.every(h=>h>=44)) }
  assert.equal(measure.toolbar.length,6)
  assert.ok(measure.toolbar.every(b=>b.width>=44&&b.height>=44))
  assert.equal(await page.getByRole('button',{name:'Fit route',exact:true}).count(),0)
  assert.equal(await page.locator('.position-inspector dt').count(),4)
  assert.equal(await page.locator('.position-inspector input').count(),0)
  assert.equal(await page.locator('summary').filter({hasText:/Location research|Walking research|Advanced settings/}).count(),0)
  await page.locator('summary').filter({hasText:'Arrival verification & safety reminders'}).click()
  assert.equal(await page.locator('.position-editor input[type="checkbox"]').count(),6)
  if([1440,1280,390].includes(width)) await page.screenshot({path:`${output}/view-${width}.png`})
  await page.getByRole('button',{name:'Edit',exact:true}).click()
  assert.equal(await page.locator('.position-inspector input').count(),4)
  if([1440,1280,390].includes(width)) await page.screenshot({path:`${output}/edit-${width}.png`})
  await page.getByLabel('Name:',{exact:true}).fill('Canceled name')
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  assert.ok(!(await page.locator('.position-values').innerText()).includes('Canceled name'))
  const search=page.getByRole('combobox',{name:'Search locations'})
  await search.fill('piata mihai')
  await page.getByRole('listbox').waitFor()
  assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(),true)
  const box=await page.getByRole('listbox').getByRole('option').boundingBox()
  assert.ok(box.x>=0 && box.x+box.width<=width)
  assert.ok(await page.evaluate(({x,y})=>!!document.elementFromPoint(x,y)?.closest('[role="option"]'),{x:box.x+10,y:box.y+10}))
  if([1440,390].includes(width)) await page.screenshot({path:`${output}/search-${width}.png`})
  if(width<640) await page.getByRole('listbox').getByRole('option').getByRole('button').tap()
  else { await search.press('ArrowDown'); await search.press('Enter') }
  await page.waitForTimeout(600)
  // Search only moves the camera under the current positioning contract. Placement is explicit.
  assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(),true)
  await page.locator('.mapboxgl-canvas').click({position:{x:120,y:300}})
  assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(),false)
  await page.getByRole('button',{name:'Confirm position',exact:true}).click()
  assert.equal(await page.locator('[data-checkpoint="4"] .position-state-confirmed').count(),1)
  await page.locator('[data-checkpoint="4"]').click()
  await page.getByRole('button',{name:'Undo last position change',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(),true)
  assert.equal(await page.getByRole('button',{name:'Undo last position change',exact:true}).isDisabled(),true)
  await page.getByRole('button',{name:'Redo last position change',exact:true}).click()
  assert.match(await page.locator('.position-inspector').innerText(),/Confirmed/)
  await page.getByRole('button',{name:'Undo last position change',exact:true}).click()
  if(width===390) {
    const canvas=page.locator('.mapboxgl-canvas')
    await canvas.tap({position:{x:120,y:300}})
    await page.waitForTimeout(400)
    assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(),false)
    const before=await page.locator('.position-values dd').nth(2).innerText()
    const marker=await page.locator('[data-position-pin="4"]').boundingBox()
    const cdp=await page.context().newCDPSession(page)
    const start={x:marker.x+marker.width/2,y:marker.y+marker.height/2}
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[start]})
    for(let n=1;n<=6;n++) await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:start.x+n*5,y:start.y+n*4}]})
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    await page.waitForTimeout(300)
    assert.notEqual(await page.locator('.position-values dd').nth(2).innerText(),before)
    await cdp.detach()
    await page.getByRole('button',{name:'Undo last position change',exact:true}).click()
    await page.getByRole('button',{name:'Undo last position change',exact:true}).click()
  }
  await page.getByRole('button',{name:'Deselect',exact:true}).click()
  await search.fill('piata mihai')
  await page.getByRole('listbox').waitFor()
  await page.getByRole('listbox').getByRole('option').getByRole('button').click()
  await page.waitForTimeout(500)
  assert.equal(await page.getByRole('button',{name:'Undo last position change',exact:true}).isDisabled(),true)
  assert.equal(await page.locator('.position-inspector dt').count(),0)
  await search.fill(''); await search.press('Escape')
  await page.locator('summary').filter({hasText:'Arrival verification & safety reminders'}).click()
}
await page.locator('[data-checkpoint="F"]').tap()
await page.getByRole('button',{name:'Edit',exact:true}).click()
await page.getByLabel('Name:',{exact:true}).fill('Edited finish')
await page.getByRole('button',{name:'Save changes',exact:true}).click()
assert.match(await page.locator('.position-values').innerText(),/Edited finish/)
const featureNavigation=page.getByRole('navigation', {name:'Hunt Features'})
assert.equal(await featureNavigation.locator('button').count(),7)
await fs.writeFile(`${output}/browser-measurements.json`,JSON.stringify({mockedMapbox:true,measurements,errors},null,2))
assert.deepEqual(errors,[])
console.log('Responsive layout, view/edit, keyboard/touch search, Deselect and confirmation/history checks passed at six widths (Mapbox mocked).')
await browser.close()
