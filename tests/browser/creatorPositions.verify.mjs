const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']})
const page = await browser.newPage({viewport:{width:1440,height:1000},hasTouch:true})
const errors=[]
page.on('pageerror',e=>errors.push(String(e)))
await page.route('https://api.mapbox.com/**',async route=> {
  if(route.request().url().includes('/styles/')) return route.fulfill({json:{version:8,sources:{},layers:[{id:'mock-background',type:'background',paint:{'background-color':'#e8eeeb'}}]}})
  if(route.request().url().includes('/suggest')) return route.fulfill({json:{suggestions:[{mapbox_id:'fixture',name:'Preview arrival area',full_address:'Local mocked search result'}]}})
  if(route.request().url().includes('/retrieve')) return route.fulfill({json:{features:[{geometry:{coordinates:[23.604,46.771]}}]}})
  return route.fulfill({json:{}})
})
await page.goto('http://127.0.0.1:5173/tests/browser/creatorPositions.html')
await page.getByRole('button',{name:/2\.Checkpoint Positions/}).click()
await page.locator('.mapboxgl-canvas').waitFor()
await page.waitForTimeout(600)
const measurements=[]
for(const width of [1440,1280,768,390,360,320]) {
  await page.setViewportSize({width,height:width<640?1200:1000})
  await page.locator('.position-feature-layout').evaluate(el=>el.closest('section').scrollIntoView({block:'start'}))
  await page.getByRole('button',{name:'Fit route',exact:true}).click()
  await page.waitForTimeout(150)
  const measure=await page.evaluate(()=>{
    const rect=s=>{const r=document.querySelector(s).getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height}}
    const main=document.querySelector('main')
    return {width:innerWidth,pageOverflow:document.documentElement.scrollWidth>innerWidth,mainOverflow:main.scrollWidth>main.clientWidth,map:rect('.position-map'),workspace:rect('.position-workspace'),list:rect('.position-checkpoints'),toolbar:[...document.querySelectorAll('.position-toolbar button')].map(b=>({label:b.textContent,width:b.getBoundingClientRect().width,height:b.getBoundingClientRect().height})),searchCount:document.querySelectorAll('[role="combobox"]').length,confirmCount:[...document.querySelectorAll('button')].filter(b=>b.textContent==='Confirm position').length}
  })
  measurements.push(measure)
  assert.equal(measure.searchCount, 1)
  assert.equal(measure.confirmCount, 1)
  assert.equal(await page.locator('.position-advanced').getAttribute('open'), null)
  assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(), true)
  const search=page.getByRole('combobox',{name:'Search locations'})
  await search.fill('Arrival')
  await page.locator('[role="listbox"] [role="option"]').waitFor()
  const bounds=await page.getByRole('listbox').boundingBox()
  assert.ok(bounds.x>=0 && bounds.x+bounds.width<=width)
  assert.ok(bounds.y>=measure.map.y && bounds.y+bounds.height<measure.map.y+measure.map.h)
  const option=await page.locator('[role="listbox"] [role="option"]').boundingBox()
  const hit=await page.evaluate(({x,y})=>document.elementFromPoint(x,y)?.closest('[role="option"]')!==null,{x:option.x+10,y:option.y+10})
  assert.ok(hit, 'Search result is hit-testable above the map')
  if(width===1440 || width===320) await page.screenshot({path:`docs/checkpoint-positions/search-${width}.png`})
  assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(), true, 'Typing cannot author geography')
  await search.press('ArrowDown'); await search.press('Enter')
  await page.getByRole('button',{name:'Confirm position',exact:true}).waitFor()
  await page.waitForTimeout(100)
  assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(), false)
  await page.getByRole('button',{name:'Confirm position',exact:true}).click()
  assert.match(await page.locator('.position-inspector-main p').innerText(), /Confirmed/)
  await page.getByRole('button',{name:'Undo last position change',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(), true)
  await page.getByRole('button',{name:'Redo last position change',exact:true}).click()
  assert.match(await page.locator('.position-inspector-main p').innerText(), /Confirmed/)
  await page.getByRole('button',{name:'Undo last position change',exact:true}).click()
  await search.fill(''); await search.press('Escape')
  if(width===390 || width===320) {
    const tapPoint = await page.locator('.mapboxgl-canvas').evaluate(canvas => {
      const r=canvas.getBoundingClientRect()
      for(const y of [.7,.8,.6]) for(const x of [.2,.4,.8]) {
        if(document.elementFromPoint(r.x+r.width*x,r.y+r.height*y)===canvas) return {x:r.width*x,y:r.height*y}
      }
      throw Error('No unobscured map tap target')
    })
    await page.tap('.mapboxgl-canvas',{position:tapPoint})
    await page.waitForTimeout(400)
    assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(), false)
    const before=await page.locator('.position-inspector-main p').innerText()
    await page.waitForTimeout(300)
    const marker=await page.locator('[data-position-pin="1"]').boundingBox()
    const session=await page.context().newCDPSession(page)
    const start={x:marker.x+marker.width/2,y:marker.y+marker.height/2}
    await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[start]})
    for(let n=1;n<=6;n++) await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:start.x+n*5,y:start.y+n*4}]})
    await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    await page.waitForTimeout(200)
    assert.notEqual(await page.locator('.position-inspector-main p').innerText(),before,'Touch dragging authors a new position')
    await session.detach()
    await page.getByRole('button',{name:'Undo last position change',exact:true}).click()
    await page.getByRole('button',{name:'Undo last position change',exact:true}).click()
  }
  // Return to the reference fixture before recording the baseline layout.
  await page.getByRole('button',{name:'Fit route',exact:true}).click()
  await page.waitForTimeout(100)
  if(measure.pageOverflow||measure.mainOverflow) throw Error(`Overflow at ${width}`)
  if(measure.toolbar.some(b=>b.width<44||b.height<44)) throw Error(`Small target at ${width}`)
  if(width>=1024&&(measure.map.w/measure.workspace.w<.70||measure.map.w/measure.workspace.w>.76))throw Error(`Map proportion at ${width}`)
  if(width!==360) await page.screenshot({path:`docs/checkpoint-positions/${width}.png`})
}
// Verify the phone strip can reach F and the feature menu restores the standard editor.
await page.locator('[data-checkpoint="F"]').tap()
assert.match(await page.locator('.position-inspector-main h4').innerText(), /^F ·/)
assert.equal(await page.getByRole('button',{name:'Confirm position',exact:true}).isDisabled(), true)
await page.locator('.position-advanced summary').first().focus()
await page.locator('.position-advanced summary').first().press('Enter')
assert.equal(await page.locator('.position-advanced').getAttribute('open'), '')
assert.equal(await page.locator('.position-advanced input').first().isVisible(), true)
await page.locator('.position-feature-navigation summary').click()
assert.equal(await page.locator('.position-feature-navigation button').count(), 9)
await page.locator('.position-feature-navigation').getByRole('button',{name:/Personal Challenge/}).click()
assert.equal(await page.locator('.position-map').count(), 0)
assert.equal(await page.locator('main > div.max-w-6xl').count(), 1)
await fs.writeFile('docs/checkpoint-positions/browser-measurements.json' ,JSON.stringify({measurements,errors},null,2))
assert.deepEqual(errors, [])
console.log('Responsive geometry, search keyboard placement, confirmation/history and mobile touch checks passed at all six widths.')
await browser.close()
