import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage()
page.setDefaultTimeout(10000)
const errors = [], results = []
page.on('pageerror', error => errors.push(String(error)))
await fs.mkdir('work/experiment-saving-browser', { recursive: true })
const feature = name => page.getByRole('navigation', { name: 'Hunt Features' }).getByRole('button', { name })
const authoring = name => page.getByRole('region', { name: `${name} Challenge authoring`, exact: true })
const checkpoint = number => page.getByRole('button', { name: number === 7 ? 'Checkpoint 7, FinishPoint' : `Checkpoint ${number}`, exact: true })
const save = () => page.getByRole('button', { name: 'Save draft', exact: true })
const submit = () => page.getByRole('button', { name: 'Submit version to Admin', exact: true })
const confirmation = () => page.getByRole('dialog', { name: 'Save without experimental exercises?', exact: true })
const calls = () => page.evaluate(() => window.fixtureCalls)
async function startCustom(name, title) {
  const panel = authoring(name)
  await panel.getByRole('button', { name: 'Create Your Own', exact: true }).click()
  await panel.getByRole('textbox', { name: 'Title', exact: true }).fill(title)
}
async function confirmSave() {
  await save().click()
  await confirmation().waitFor()
  await confirmation().getByRole('button', { name: 'Save supported settings only', exact: true }).click()
  await confirmation().waitFor({ state: 'detached' })
}
for (const width of [1440, 768, 390, 320]) {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('http://127.0.0.1:5173/tests/browser/exerciseLibrary.html')
  await feature(/Personal Challenge/).click()
  const original = await page.evaluate(() => window.fixtureRecord())
  // Existing supported assignments save and reopen without any confirmation or custom data.
  await authoring('Personal').getByRole('combobox', { name: 'Personal Challenge', exact: true }).selectOption('radial')
  await save().click()
  assert.equal(await confirmation().count(), 0)
  assert.equal((await calls()).length, 1)
  await page.evaluate(() => window.fixtureReopen()); await feature(/Personal Challenge/).click()
  assert.equal(await authoring('Personal').getByRole('combobox', { name: 'Personal Challenge', exact: true }).inputValue(), 'radial')
  await startCustom('Personal', 'Unsaved checkpoint one')
  await authoring('Personal').getByRole('combobox', { name: 'Exercise type', exact: true }).selectOption('true-false')
  await authoring('Personal').getByRole('textbox', { name: 'Title', exact: true }).fill('Retained truth variant')
  await authoring('Personal').getByRole('combobox', { name: 'Exercise type', exact: true }).selectOption('tap-pair')
  assert.equal(await authoring('Personal').getByRole('textbox', { name: 'Title', exact: true }).inputValue(), 'Unsaved checkpoint one')
  await checkpoint(2).click(); await startCustom('Personal', 'Unsaved checkpoint two')
  await checkpoint(7).click(); await startCustom('Personal', 'Unsaved FinishPoint')
  await feature(/Team Challenge/).click(); await checkpoint(1).click(); await startCustom('Team', 'Unsaved team one')
  await feature(/Personal Challenge/).click(); await checkpoint(1).click()
  assert.equal(await authoring('Personal').getByRole('textbox', { name: 'Title', exact: true }).inputValue(), 'Unsaved checkpoint one')
  // Preview includes current unsaved content; dismissal preserves it.
  await authoring('Personal').getByRole('button', { name: 'Preview Exercise', exact: true }).click()
  assert.match(await page.getByRole('dialog', { name: 'Exercise preview' }).textContent(), /Unsaved checkpoint one/)
  await page.keyboard.press('Escape')
  await authoring('Personal').getByRole('button', { name: 'Predefined', exact: true }).click()
  await authoring('Personal').getByRole('combobox', { name: 'Personal Challenge', exact: true }).selectOption('identify-signal')
  assert.equal(await submit().isDisabled(), true) // Browsing/choosing supported content does not clear experiment intent.
  await save().click()
  const warning = confirmation()
  assert.match(await warning.textContent(), /will be excluded/)
  for (const label of ['Personal Challenge · Checkpoint 1', 'Personal Challenge · Checkpoint 2', 'Personal Challenge · FinishPoint', 'Team Challenge · Checkpoint 1']) assert.match(await warning.textContent(), new RegExp(label))
  assert.equal(await warning.getByRole('button', { name: 'Cancel', exact: true }).evaluate(node => document.activeElement === node), true)
  await page.keyboard.press('Shift+Tab')
  assert.equal(await warning.getByRole('button', { name: 'Save supported settings only', exact: true }).evaluate(node => document.activeElement === node), true)
  await page.keyboard.press('Tab'); await page.keyboard.press('Escape')
  assert.equal(await save().evaluate(node => document.activeElement === node), true)
  assert.equal((await calls()).length, 1)
  await save().click(); await warning.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal((await calls()).length, 1)
  await save().click()
  assert.equal(await warning.evaluate(node => node.scrollWidth > node.clientWidth), false)
  await page.screenshot({ path: `work/experiment-saving-browser/confirmation-${width}.png` })
  await warning.getByRole('button', { name: 'Save supported settings only', exact: true }).click()
  await warning.waitFor({ state: 'detached' })
  await page.getByText('Supported template configuration is saved.', { exact: false }).waitFor()
  const savedCalls = await calls()
  assert.equal(savedCalls.length, 2)
  const saved = savedCalls[1].content
  assert.equal(saved.checkpoints[0].kind, 'identify-signal')
  assert.deepEqual(saved.checkpoints.slice(1), original.content.checkpoints.slice(1))
  for (const marker of ['Unsaved checkpoint one', 'Unsaved checkpoint two', 'Unsaved FinishPoint', 'Unsaved team one', 'intendedForSubmission', 'local-example:', 'custom:']) assert.equal(JSON.stringify(saved).includes(marker), false)
  assert.equal(await submit().isDisabled(), true)
  await authoring('Personal').getByRole('button', { name: 'Create Your Own', exact: true }).click()
  assert.equal(await authoring('Personal').getByRole('textbox', { name: 'Title', exact: true }).inputValue(), 'Unsaved checkpoint one')
  // Explicit discard removes one slot, preserving the other class and terminal drafts.
  await authoring('Personal').getByRole('button', { name: 'Discard Experiment', exact: true }).click()
  assert.equal(await authoring('Personal').getByRole('textbox', { name: 'Title', exact: true }).count(), 0)
  await checkpoint(2).click()
  assert.equal(await authoring('Personal').getByRole('textbox', { name: 'Title', exact: true }).inputValue(), 'Unsaved checkpoint two')
  await authoring('Personal').getByRole('button', { name: 'Discard Experiment', exact: true }).click()
  await checkpoint(7).click()
  assert.equal(await authoring('Personal').getByRole('textbox', { name: 'Title', exact: true }).inputValue(), 'Unsaved FinishPoint')
  await authoring('Personal').getByRole('checkbox', { name: 'Intend to include this experiment in the submitted template' }).uncheck()
  await feature(/Team Challenge/).click(); await checkpoint(1).click()
  assert.equal(await authoring('Team').getByRole('textbox', { name: 'Title', exact: true }).inputValue(), 'Unsaved team one')
  assert.equal(await submit().isDisabled(), true)
  await authoring('Team').getByRole('checkbox', { name: 'Intend to include this experiment in the submitted template' }).uncheck()
  assert.equal(await submit().isDisabled(), false) // Only explicit intent choices can permit supported-only submission.
  await confirmSave() // Even preview-only retained content needs disclosure on each save.
  assert.equal((await calls()).length, 2) // No duplicate immutable version for unchanged supported configuration.
  await feature(/Personal Challenge/).click(); await checkpoint(7).click()
  assert.equal(await authoring('Personal').getByRole('textbox', { name: 'Title', exact: true }).inputValue(), 'Unsaved FinishPoint')
  assert.equal(await authoring('Personal').getByRole('checkbox', { name: 'Intend to include this experiment in the submitted template' }).isChecked(), false)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.querySelector('main').scrollWidth > innerWidth)
  assert.equal(overflow, false)
  results.push({ width, supportedSaveAndReopen: true, confirmationRequired: true, cancelAndEscapeSafe: true, excludedPayload: true, draftsRetainedAfterSave: true, targetedDiscard: true, submissionIntentPreserved: true, explicitPreviewOnly: true, noDuplicateVersion: true, overflow })
}
assert.deepEqual(errors, [])
await fs.writeFile('work/experiment-saving-browser/results.json', JSON.stringify({ results, errors, backend: 'mocked fixture; no live FE–BE integration' }, null, 2))
console.log(JSON.stringify({ workflows: results.length, results, errors }))
await browser.close()
