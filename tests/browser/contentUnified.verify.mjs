import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const dir = 'work/c1-2-screenshots'
await mkdir(dir, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage()
const url = 'http://127.0.0.1:5173/tests/browser/contentUnified.html'
for (const width of [1440, 390, 320]) {
  await page.setViewportSize({ width, height: 960 }); await page.goto(url)
  await page.getByRole('button', { name: 'Edit with Preview', exact: true }).waitFor()
  await page.getByLabel('Title', { exact: true }).fill('Preserved draft title')
  await page.getByRole('button', { name: 'Complex / LaTeX', exact: true }).click()
  await page.getByRole('button', { name: 'Edit with Preview', exact: true }).click()
  assert.equal(await page.getByLabel('Title', { exact: true }).inputValue(), 'Preserved draft title')
  assert.equal(await page.getByRole('button', { name: 'Apply challenge', exact: true }).count(), 0)
  await page.screenshot({ path: `${dir}/personal-editor-${width}.png`, fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `personal overflow ${width}`)
  page.once('dialog', dialog => dialog.dismiss()); await page.getByRole('link', { name: 'Leave Content' }).click()
  assert.equal(await page.getByRole('heading', { name: 'Content', exact: true }).count(), 1)
  await page.getByRole('button', { name: 'Library', exact: true }).click(); await page.getByText('Filters', { exact: true }).click()
  for (const label of ['Content country', 'Content region', 'Content city']) assert.equal(await page.getByLabel(label).inputValue(), '')
  const starter = page.locator('details').filter({ has: page.locator('summary', { hasText: /^Starter/ }) })
  assert.equal(await starter.getAttribute('open'), null)
  await page.screenshot({ path: `${dir}/library-${width}.png`, fullPage: true })
  await page.getByLabel('Content category').selectOption('Mathematics')
  await page.getByText('Mathematics curriculum', { exact: true }).click()
  for (const label of ['Grade', 'Main', 'Unit', 'Lesson']) assert.equal(await page.getByRole('combobox', { name: label, exact: true }).isDisabled(), true)
  await page.screenshot({ path: `${dir}/mathematics-filters-${width}.png`, fullPage: true })
  await page.getByLabel('Content category').selectOption('History')
  assert.equal(await page.getByRole('combobox', { name: 'Grade', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await page.getByLabel('Content country').selectOption('RO'); await page.getByLabel('Content region').selectOption('fixture-region')
  await page.getByLabel('Find content city').fill('Fi'); await page.getByLabel('Content city', { exact: true }).selectOption('fixture-city')
  await page.getByLabel('Content country').selectOption('FR')
  assert.equal(await page.getByLabel('Content region').inputValue(), ''); assert.equal(await page.getByLabel('Content city', { exact: true }).inputValue(), '')
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await starter.locator('summary').click()
  await page.getByRole('button', { name: /^Preview / }).first().click()
  await page.getByRole('dialog').waitFor(); await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Create Content', exact: true }).click()
  assert.equal(await page.getByLabel('Title', { exact: true }).inputValue(), 'Preserved draft title')
  await page.getByRole('button', { name: 'Team Challenges', exact: true }).click()
  await page.screenshot({ path: `${dir}/team-editor-${width}.png`, fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `team overflow ${width}`)
  await page.getByRole('button', { name: 'Navigation Hints', exact: true }).click()
  assert.equal(await page.getByRole('region', { name: 'Library exercise draft', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Personal Challenges', exact: true }).click()
  assert.equal(await page.getByLabel('Title', { exact: true }).inputValue(), 'Preserved draft title')
  // Check Template's shared individual picker without discarding session drafts in the first tab.
  const template = await browser.newPage({ viewport: { width, height: 960 } })
  await template.goto(url + '?template=1')
  await template.getByRole('button', { name: /^Try example:/ }).first().click()
  assert.equal(await template.getByRole('button', { name: 'Apply challenge', exact: true }).count(), 0)
  await template.screenshot({ path: `${dir}/template-picker-${width}.png`, fullPage: true })
  assert.ok(await template.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Template picker overflow ${width}`)
  await template.close()
}
await browser.close()
console.log('C1.2 Library, Personal/Team editors, draft protection, shared Template picker: passed at 1440, 390, 320px.')
