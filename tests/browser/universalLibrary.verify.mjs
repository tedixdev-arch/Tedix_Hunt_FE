import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage()
const errors = [], mutations = [], measurements = []
page.on('pageerror', error => errors.push(String(error)))
page.on('request', request => { if (!['GET', 'HEAD'].includes(request.method())) mutations.push(request.url()) })
await fs.mkdir('work/universal-library-browser', { recursive: true })
for (const width of [1440, 768, 390, 320]) {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('http://127.0.0.1:5173/tests/browser/universalLibrary.html')
  const library = page.getByRole('region', { name: 'Universal Library', exact: true })
  const refresh = library.getByRole('button', { name: 'Refresh Library', exact: true })
  const view = library.getByRole('button', { name: 'View approved Template', exact: true })
  await view.waitFor()
  await refresh.focus(); await page.keyboard.press('Tab')
  assert.equal(await view.evaluate(node => document.activeElement === node), true)
  await page.keyboard.press('Shift+Tab')
  assert.equal(await refresh.evaluate(node => document.activeElement === node), true)
  await page.keyboard.press('Tab'); await page.keyboard.press('Enter')
  const detail = page.getByRole('article', { name: 'Approved Universal Template' })
  await detail.waitFor()
  assert.equal((await library.textContent()).includes('Published version 3'), true)
  assert.equal((await library.textContent()).includes('Published version 1'), false)
  assert.equal((await detail.textContent()).includes('Publication changed since the Library was loaded'), true)
  assert.equal(await detail.locator('h3').evaluate(node => document.activeElement === node), true)
  assert.equal(await detail.locator('input,textarea,select,a').count(), 0)
  assert.equal(await detail.getByRole('button', { name: 'Use as Local Template', exact: true }).count(), 1)
  const measure = await library.evaluate(node => ({ width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth || node.scrollWidth > node.clientWidth }))
  assert.equal(measure.overflow, false); measurements.push(measure)
  await page.screenshot({ path: `work/universal-library-browser/library-${width}.png`, fullPage: true })
  await detail.getByRole('heading', { name: 'FinishPoint', exact: true }).scrollIntoViewIfNeeded()
  assert.equal(await detail.getByRole('heading', { name: 'FinishPoint', exact: true }).isVisible(), true)
  await page.screenshot({ path: `work/universal-library-browser/content-${width}.png`, fullPage: true })
}
assert.deepEqual(errors, []); assert.deepEqual(mutations, [])
console.log(JSON.stringify({ measurements, errors, mutations }))
await browser.close()
